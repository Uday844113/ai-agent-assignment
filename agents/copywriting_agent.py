# User-facing labels for the UI dropdown
AD_TYPES = {
    "facebook": "Facebook Ads",
    "google": "Google Ads",
    "linkedin": "LinkedIn Ads",
    "product": "Product Description",
    "email": "Email Copy",
    "cta": "CTA Variations",
}


class CopywritingAgent:
    """Agent for generating ads, product copy, email copy, and CTAs."""

    def __init__(self, openrouter_client: OpenRouterClient = None):
        self.client = openrouter_client

    # ------------------------------------------------------------------
    # Public API
    # ------------------------------------------------------------------

    def get_ad_types(self) -> Dict[str, str]:
        """Return the available ad / copy types as {key: label}."""
        return AD_TYPES

    def generate(
        self,
        ad_type: str,
        product: str,
        platform: str,
        target_audience: str,
        campaign_objective: str,
        tone: str,
        key_benefit: str = "",
        extra_context: str = "",
        demo_mode: bool = False,
        demo_variant: int = 0,
    ) -> str:
        """
        Generate ad / copy content via OpenRouter or return a demo output.

        Parameters
        ----------
        ad_type : str
            One of the keys in ``AD_TYPES``.
        product : str
            The product, service, or topic.
        platform : str
            The advertising platform (e.g. "Facebook", "Google Ads").
        target_audience : str
            Who the copy is aimed at.
        campaign_objective : str
            The campaign objective (e.g. "Lead Generation").
        tone : str
            Desired tone (e.g. "professional", "playful").
        key_benefit : str
            The main value proposition or key benefit.
        extra_context : str
            Additional notes (benefits, features, URLs, etc.).
        demo_mode : bool
            If True, return a pre-written demo output.
        demo_variant : int
            Which demo sample to return (0, 1, or 2).

        Returns
        -------
        str
            Generated or demo content as formatted markdown.
        """
        if demo_mode:
            return self._get_demo_output(ad_type, demo_variant)

        if self.client is None:
            raise RuntimeError(
                "No OpenRouter client available. Ensure OPENROUTER_API_KEY is set "
                "or enable Demo Mode."
            )

        user_prompt = self._build_prompt(
            ad_type, product, platform, target_audience,
            campaign_objective, tone, key_benefit, extra_context
        )

        try:
            raw = self.client.generate(
                system_prompt=COPYWRITING_SYSTEM_PROMPT,
                user_prompt=user_prompt,
            )
            parsed = self._extract_and_validate(raw, ad_type)
            return self._render_output(parsed, ad_type)
        except Exception as exc:
            raise RuntimeError(f"Failed to generate copy: {exc}") from exc

    # ------------------------------------------------------------------
    # Internal helpers
    # ------------------------------------------------------------------

    def _build_prompt(
        self,
        ad_type: str,
        product: str,
        platform: str,
        target_audience: str,
        campaign_objective: str,
        tone: str,
        key_benefit: str,
        extra_context: str,
    ) -> str:
        """Select the matching template and inject variables safely."""
        template_map = {
            "facebook": FACEBOOK_ADS_TEMPLATE,
            "google": GOOGLE_ADS_TEMPLATE,
            "linkedin": LINKEDIN_ADS_TEMPLATE,
            "product": PRODUCT_DESCRIPTION_TEMPLATE,
            "email": EMAIL_COPY_TEMPLATE,
            "cta": CTA_VARIATIONS_TEMPLATE,
        }

        template = template_map.get(ad_type)
        if template is None:
            raise ValueError(f"Unknown ad type: {ad_type}")

        benefits = key_benefit if key_benefit else extra_context if extra_context else "Key differentiators"
        features = extra_context if extra_context else "Core features"
        url = extra_context if extra_context else "https://example.com"
        product_name = product
        category = extra_context if extra_context else "General"
        purpose = extra_context if extra_context else "Product promotion"

        field_map = {
            "facebook": {
                "product": product,
                "platform": platform,
                "benefits": benefits,
                "target_audience": target_audience,
                "tone": tone,
                "campaign_objective": campaign_objective,
            },
            "google": {
                "product": product,
                "platform": platform,
                "keyword": product,
                "target_audience": target_audience,
                "tone": tone,
                "url": url,
                "campaign_objective": campaign_objective,
            },
            "linkedin": {
                "product": product,
                "platform": platform,
                "benefits": benefits,
                "target_audience": target_audience,
                "tone": tone,
                "campaign_objective": campaign_objective,
            },
            "product": {
                "product_name": product_name,
                "platform": platform,
                "category": category,
                "features": features,
                "target_audience": target_audience,
                "tone": tone,
                "campaign_objective": campaign_objective,
            },
            "email": {
                "product": product,
                "platform": platform,
                "purpose": purpose,
                "target_audience": target_audience,
                "tone": tone,
                "campaign_objective": campaign_objective,
            },
            "cta": {
                "product": product,
                "platform": platform,
                "action": extra_context if extra_context else "convert",
                "target_audience": target_audience,
                "tone": tone,
                "campaign_objective": campaign_objective,
            },
        }

        prompt = template
        for key, value in field_map[ad_type].items():
            placeholder = "{" + key + "}"
            prompt = prompt.replace(placeholder, str(value))

        return prompt

    def _extract_and_validate(self, raw: str, ad_type: str) -> dict:
        """Extract JSON from raw response, retry once if needed, then validate."""
        try:
            parsed = OpenRouterClient.extract_json_text(raw)
        except ValueError:
            parsed = self._retry_json_extraction(ad_type, raw)

        if ad_type == "facebook":
            self._validate_facebook_constraints(parsed)

        return parsed

    def _retry_json_extraction(self, ad_type: str, raw: str) -> dict:
        """Retry once with a strict JSON correction prompt."""
        strict_prompt = (
            "CRITICAL: Your previous response could not be parsed as valid JSON. "
            "Return ONLY valid JSON. No markdown, no explanations, no reasoning, no analysis. "
            "The response must begin with { and end with }. "
            "Do not count characters. Do not explain your work.\n\n"
            "Required JSON schema:\n"
            "{\n"
            '  "variations": [\n'
            "    {\n"
            '      "primary_text": "...",\n'
            '      "headline": "...",\n'
            '      "description": "...",\n'
            '      "cta": "..."\n'
            "    }\n"
            "  ]\n"
            "}"
        )
        retry_raw = self.client.generate(
            system_prompt=COPYWRITING_SYSTEM_PROMPT,
            user_prompt=strict_prompt,
        )
        return OpenRouterClient.extract_json_text(retry_raw)

    @staticmethod
    def _validate_facebook_constraints(data: dict) -> None:
        """Validate Facebook Ads character limits. Silently truncate if needed."""
        variations = data.get("variations", [])
        for variation in variations:
            primary_text = variation.get("primary_text", "")
            if len(primary_text) > 90:
                variation["primary_text"] = primary_text[:87] + "..."

            headline = variation.get("headline", "")
            if len(headline) > 40:
                variation["headline"] = headline[:37] + "..."

            description = variation.get("description", "")
            if len(description) > 30:
                variation["description"] = description[:27] + "..."

    def _render_output(self, data: dict, ad_type: str) -> str:
        """Render parsed JSON as clean markdown for display."""
        if ad_type == "facebook":
            return self._render_facebook(data)
        if ad_type == "google":
            return self._render_google(data)
        if ad_type == "linkedin":
            return self._render_linkedin(data)
        if ad_type == "product":
            return self._render_product(data)
        if ad_type == "email":
            return self._render_email(data)
        if ad_type == "cta":
            return self._render_cta(data)
        return json.dumps(data, indent=2)

    def _render_facebook(self, data: dict) -> str:
        parts = ["# Facebook Ad Variations"]
        variations = data.get("variations", [])
        for i, v in enumerate(variations, 1):
            parts.append(f"## Variation {i}")
            parts.append(f"**Primary Text:** {v.get('primary_text', '')}")
            parts.append(f"**Headline:** {v.get('headline', '')}")
            parts.append(f"**Description:** {v.get('description', '')}")
            parts.append(f"**CTA:** {v.get('cta', '')}")
            if i < len(variations):
                parts.append("---")
        return "\n\n".join(parts)

    def _render_google(self, data: dict) -> str:
        parts = ["# Google Search Ad Variations"]
        variations = data.get("variations", [])
        for i, v in enumerate(variations, 1):
            parts.append(f"## Variation {i}")
            headlines = v.get("headlines", [])
            if headlines:
                parts.append("**Headlines:**")
                parts.extend(f"- {h}" for h in headlines)
            descriptions = v.get("descriptions", [])
            if descriptions:
                parts.append("**Descriptions:**")
                parts.extend(f"- {d}" for d in descriptions)
            final_url = v.get("final_url", "")
            if final_url:
                parts.append(f"**Final URL:** {final_url}")
            if i < len(variations):
                parts.append("---")
        return "\n\n".join(parts)

    def _render_linkedin(self, data: dict) -> str:
        parts = ["# LinkedIn Ad Variations"]
        variations = data.get("variations", [])
        for i, v in enumerate(variations, 1):
            parts.append(f"## Variation {i}")
            headline = v.get("headline", "")
            if headline:
                parts.append(f"**Headline:** {headline}")
            body = v.get("body", "")
            if body:
                parts.append(f"**Body text:**")
                parts.append(body)
            cta = v.get("cta", "")
            if cta:
                parts.append(f"**CTA Button:** {cta}")
            if i < len(variations):
                parts.append("---")
        return "\n\n".join(parts)

    def _render_product(self, data: dict) -> str:
        parts = ["# Product Descriptions"]
        title = data.get("title", "")
        if title:
            parts.append(f"## Product Title\n**{title}**")
        meta = data.get("meta_description", "")
        if meta:
            parts.append(f"## Meta Description\n**{meta}**")
        full = data.get("full_description", "")
        if full:
            parts.append(f"## Full Description\n{full}")
        bullets = data.get("bullet_points", [])
        if bullets:
            parts.append("## Amazon Bullet Points")
            parts.extend(f"- {b}" for b in bullets)
        return "\n\n".join(parts)

    def _render_email(self, data: dict) -> str:
        parts = ["# Email Campaign"]
        subject = data.get("subject", "")
        if subject:
            parts.append(f"**Subject:** {subject}")
        preheader = data.get("preheader", "")
        if preheader:
            parts.append(f"**Pre-header text:** {preheader}")
        body = data.get("body", "")
        if body:
            parts.append(f"**Email body:**")
            parts.append(body)
        ps = data.get("ps", "")
        if ps:
            parts.append(f"**P.S.** {ps}")
        return "\n\n".join(parts)

    def _render_cta(self, data: dict) -> str:
        parts = ["# CTA Variations"]
        ctas = data.get("ctas", [])
        for i, c in enumerate(ctas, 1):
            parts.append(f"{i}. {c}")
        return "\n\n".join(parts)

    def _get_demo_output(self, ad_type: str, variant: int) -> str:
        """Return a pre-written demo output for the given ad type."""
        outputs = DEMO_OUTPUTS.get(ad_type, [])
        if not outputs:
            return "No demo output available for this type."
        variant = variant % len(outputs)
        return outputs[variant]
