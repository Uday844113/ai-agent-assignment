class ContentAgent:
    """Agent for generating blog posts, website copy, e-book content, etc."""

    # The set of content types this agent supports, mapped to
    # human-readable labels and their demo output keys.
    CONTENT_TYPES = {
        "blog": "Blog Post",
        "website": "Website Content",
        "ebook": "E-book Content",
        "seo": "SEO Article",
    }

    def __init__(self, openrouter_client: OpenRouterClient = None):
        """
        Parameters
        ----------
        openrouter_client : OpenRouterClient | None
            A configured OpenRouter client.  Pass ``None`` when using demo
            mode only.
        """
        self.client = openrouter_client

    # ------------------------------------------------------------------
    # Public API
    # ------------------------------------------------------------------

    def get_content_types(self) -> Dict[str, str]:
        """Return the available content types as {key: label}."""
        return self.CONTENT_TYPES

    def generate(
        self,
        content_type: str,
        topic: str,
        target_audience: str,
        tone: str,
        word_count: int,
        keywords: str = "",
        extra_context: str = "",
        demo_mode: bool = False,
        demo_variant: int = 0,
    ) -> str:
        """
        Generate content via OpenRouter or return a demo output.

        Parameters
        ----------
        content_type : str
            One of the keys in ``CONTENT_TYPES``.
        topic : str
            The main subject or title of the content.
        target_audience : str
            Who the content is aimed at.
        tone : str
            Desired tone (e.g. "professional", "casual").
        word_count : int
            Approximate desired length.
        keywords : str
            Comma-separated keywords to include in the content.
        extra_context : str
            Any additional instructions from the user.
        demo_mode : bool
            If True, return a pre-written demo output instead of
            calling the OpenRouter API.
        demo_variant : int
            Which demo sample to return (0, 1, or 2).

        Returns
        -------
        str
            The generated or demo content.
        """
        if demo_mode:
            return self._get_demo_output(content_type, demo_variant)

        if self.client is None:
            raise RuntimeError(
                "No OpenRouter client available. Ensure OPENROUTER_API_KEY is set "
                "or enable Demo Mode."
            )

        system = CONTENT_SYSTEM_PROMPT
        user_prompt = self._build_prompt(
            content_type, topic, target_audience, tone, word_count, keywords, extra_context
        )

        try:
            raw = self.client.generate(system_prompt=system, user_prompt=user_prompt)
            parsed = self._extract_and_validate(raw)
            return self._render_output(parsed, content_type)
        except Exception as exc:
            raise RuntimeError(f"Failed to generate content: {exc}") from exc

    # ------------------------------------------------------------------
    # Internal helpers
    # ------------------------------------------------------------------

    def _build_prompt(
        self,
        content_type: str,
        topic: str,
        target_audience: str,
        tone: str,
        word_count: int,
        keywords: str,
        extra_context: str,
    ) -> str:
        """Select the right template and fill in the variables safely."""
        base_data = {
            "topic": topic,
            "target_audience": target_audience,
            "tone": tone,
            "word_count": word_count,
        }

        if content_type == "blog":
            template = BLOG_POST_TEMPLATE
            base_data["keywords"] = keywords or "relevant keywords"
        elif content_type == "website":
            template = WEBSITE_CONTENT_TEMPLATE
            base_data["content_type"] = self._resolve_content_type(topic)
            base_data["brand_name"] = topic
            base_data["industry"] = extra_context or "General"
        elif content_type == "ebook":
            template = EBOOK_CONTENT_TEMPLATE
            base_data["chapter_title"] = topic
            base_data["subject"] = extra_context or topic
            base_data["ebook_theme"] = topic
        elif content_type == "seo":
            template = SEO_ARTICLE_TEMPLATE
            base_data["topic"] = topic
            base_data["primary_keyword"] = topic
            base_data["seo_title"] = topic
            base_data["keywords"] = keywords or topic
            base_data["extra_context"] = extra_context or ""
        else:
            raise ValueError(f"Unknown content type: {content_type}")

        prompt = template
        for key, value in base_data.items():
            placeholder = "{" + key + "}"
            prompt = prompt.replace(placeholder, str(value))

        if extra_context and content_type not in ("website", "seo"):
            prompt += f"\n\nAdditional context: {extra_context}"

        return prompt

    def _extract_and_validate(self, raw: str) -> dict:
        """Extract JSON from raw response, retry once if needed."""
        try:
            parsed = OpenRouterClient.extract_json_text(raw)
        except ValueError:
            parsed = self._retry_json_extraction()
        return parsed

    def _retry_json_extraction(self) -> dict:
        """Retry once with a strict JSON correction prompt."""
        strict_prompt = (
            "CRITICAL: Your previous response could not be parsed as valid JSON. "
            "Return ONLY valid JSON. No markdown, no explanations, no reasoning, no analysis. "
            "The response must begin with { and end with }. "
            "Do not count words. Do not explain your work.\n\n"
            "Required JSON schema:\n"
            "{\n"
            '  "title": "Content title",\n'
            '  "content": "Full content with markdown headings"\n'
            "}"
        )
        retry_raw = self.client.generate(
            system_prompt=CONTENT_SYSTEM_PROMPT,
            user_prompt=strict_prompt,
        )
        return OpenRouterClient.extract_json_text(retry_raw)

    def _render_output(self, data: dict, content_type: str) -> str:
        """Render parsed JSON as clean markdown for display."""
        if content_type == "website":
            return self._render_website(data)
        return data.get("content", json.dumps(data, indent=2))

    def _render_website(self, data: dict) -> str:
        parts = []
        headline = data.get("headline", "")
        if headline:
            parts.append(f"# {headline}")
        subheadline = data.get("subheadline", "")
        if subheadline:
            parts.append(f"## {subheadline}")
        hero = data.get("hero", "")
        if hero:
            parts.append(hero)
        benefits = data.get("benefits", [])
        if benefits:
            parts.append("## Key Benefits")
            parts.extend(f"- {b}" for b in benefits)
        about = data.get("about", "")
        if about:
            parts.append("## About")
            parts.append(about)
        cta = data.get("cta", "")
        if cta:
            parts.append(f"## Call to Action\n\n{cta}")
        return "\n\n".join(parts)

    def _resolve_content_type(self, topic: str) -> str:
        """
        Infer a website page type (e.g. 'landing', 'about') from the
        topic string.  Falls back to 'landing' if nothing matches.
        """
        topic_lower = topic.lower()
        for page_type in ["about", "pricing", "contact", "home", "services", "landing"]:
            if page_type in topic_lower:
                return page_type
        return "landing"

    def _get_demo_output(self, content_type: str, variant: int) -> str:
        """Return a pre-written demo output for the given content type."""
        outputs = DEMO_OUTPUTS.get(content_type, [])
        if not outputs:
            return "No demo output available for this content type."
        variant = variant % len(outputs)
        return outputs[variant]
