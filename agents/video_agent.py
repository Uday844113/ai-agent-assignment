# User-facing labels
VIDEO_TYPES = {
    "script": "Video Script",
    "storyboard": "Storyboard",
    "shotlist": "Shot List",
    "voiceover": "Voice-Over Script",
    "social": "Social Media Video",
}


class VideoAgent:
    """Agent for generating scripts, storyboards, shot lists, etc."""

    def __init__(self, openrouter_client: OpenRouterClient = None):
        self.client = openrouter_client

    # ------------------------------------------------------------------
    # Public API
    # ------------------------------------------------------------------

    def get_video_types(self) -> Dict[str, str]:
        """Return the available video content types as {key: label}."""
        return VIDEO_TYPES

    def generate(
        self,
        video_type: str,
        topic: str,
        duration: str,
        target_audience: str,
        tone: str,
        platform: str = "",
        cta: str = "",
        extra_context: str = "",
        demo_mode: bool = False,
        demo_variant: int = 0,
        video_type_detail: str = "",
    ) -> str:
        """
        Generate video content via OpenRouter or return a demo output.

        Parameters
        ----------
        video_type : str
            One of the keys in ``VIDEO_TYPES``.
        topic : str
            The main subject of the video.
        duration : str
            Target length (e.g. "60 seconds").
        target_audience : str
            Who the video is aimed at.
        tone : str
            Desired tone (e.g. "professional", "fun", "dramatic").
        platform : str
            Social media platform (only used for social video).
        cta : str
            Call to action for the video.
        extra_context : str
            Additional notes (scene count, camera, etc.).
        demo_mode : bool
            If True, return a pre-written demo output.
        demo_variant : int
            Which demo sample to return (0, 1, or 2).
        video_type_detail : str
            Optional detail for the video type (e.g. "explainer", "ad").

        Returns
        -------
        str
            Generated or demo content.
        """
        if demo_mode:
            return self._get_demo_output(video_type, demo_variant)

        if self.client is None:
            raise RuntimeError(
                "No OpenRouter client available. Ensure OPENROUTER_API_KEY is set "
                "or enable Demo Mode."
            )

        system = VIDEO_SYSTEM_PROMPT
        user_prompt = self._build_prompt(
            video_type, topic, duration, video_type_detail,
            target_audience, tone, platform, cta, extra_context
        )

        try:
            raw = self.client.generate(system_prompt=system, user_prompt=user_prompt)
            return self._validate_and_format(raw, video_type)
        except Exception as exc:
            raise RuntimeError(f"Failed to generate video content: {exc}") from exc

    # ------------------------------------------------------------------
    # Internal helpers
    # ------------------------------------------------------------------

    def _validate_and_format(self, raw: str, video_type: str) -> str:
        """
        Try to parse the raw response as JSON using the expected schema.
        If parsing fails, retry once with a stricter JSON-only instruction.
        If it still fails, return a clean error message.
        """
        try:
            parsed = OpenRouterClient.extract_json_text(raw)
        except ValueError:
            parsed = self._retry_json_extraction()

        if parsed is not None:
            return self._format_json_output(parsed, video_type)

        return "Unable to generate structured video output. Please try again."

    def _retry_json_extraction(self) -> Optional[dict]:
        stricter_prompt = (
            "CRITICAL: Return ONLY valid JSON. No markdown, no explanations, "
            "no reasoning, no analysis, no planning, no extra text. "
            "The response must begin with { and end with }.\n\n"
            "Required JSON schema:\n"
            '{\n'
            '  "title": "...",\n'
            '  "hook": "...",\n'
            '  "script": "...",\n'
            '  "scenes": [{"scene": "S1", "timestamp": "0:00-0:05", "visual": "...", "voiceover": "...", "camera": "...", "audio": "..."}],\n'
            '  "storyboard": [{"scene": "S1", "visual": "...", "on_screen_text": "..."}],\n'
            '  "shot_list": [{"shot": "1", "description": "...", "camera": "...", "audio": "...", "notes": "..."}],\n'
            '  "voiceover": "...",\n'
            '  "on_screen_text": ["..."],\n'
            '  "cta": "..."\n'
            '}\n\n'
            "Return ONLY this JSON. Nothing else."
        )
        try:
            retry_raw = self.client.generate(
                system_prompt=VIDEO_SYSTEM_PROMPT,
                user_prompt=stricter_prompt,
            )
            return OpenRouterClient.extract_json_text(retry_raw)
        except Exception:
            return None

    @staticmethod
    def _try_parse_json(text: str) -> Optional[dict]:
        text = text.strip()
        if text.startswith("```"):
            lines = text.splitlines()
            if lines[0].startswith("```"):
                lines = lines[1:]
            if lines and lines[-1].strip() == "```":
                lines = lines[:-1]
            text = "\n".join(lines).strip()
        try:
            parsed = json.loads(text)
            if isinstance(parsed, dict):
                return parsed
        except (json.JSONDecodeError, ValueError):
            pass
        return None

    def _format_json_output(self, data: dict, video_type: str) -> str:
        parts = []

        if video_type == "script":
            title = data.get("title", "")
            hook = data.get("hook", "")
            script = data.get("script", "")
            scenes = data.get("scenes", [])
            cta = data.get("cta", "")

            if title:
                parts.append(f"# {title}")
            if hook:
                parts.append(f"## Hook\n\n{hook}")
            if script:
                parts.append(f"## Script\n\n{script}")
            for scene in scenes:
                scene_num = scene.get("scene", "")
                timestamp = scene.get("timestamp", "")
                visual = scene.get("visual", "")
                voiceover = scene.get("voiceover", "")
                camera = scene.get("camera", "")
                audio = scene.get("audio", "")
                parts.append(
                    f"### [{timestamp}] {scene_num}\n\n"
                    f"**Visual:** {visual}\n\n"
                    f"**Voice-over (V.O.):** {voiceover}\n\n"
                    f"**Camera:** {camera}\n\n"
                    f"**Audio:** {audio}"
                )
            if cta:
                parts.append(f"## Call to Action\n\n{cta}")

        elif video_type == "storyboard":
            title = data.get("title", "")
            storyboard = data.get("storyboard", [])
            cta = data.get("cta", "")

            if title:
                parts.append(f"# {title}")
            for frame in storyboard:
                scene = frame.get("scene", "")
                visual = frame.get("visual", "")
                on_screen_text = frame.get("on_screen_text", "")
                parts.append(
                    f"## {scene}\n\n"
                    f"**Visual:** {visual}\n\n"
                    f"**On-screen text:** {on_screen_text}"
                )
            if cta:
                parts.append(f"## Call to Action\n\n{cta}")

        elif video_type == "shotlist":
            title = data.get("title", "")
            shot_list = data.get("shot_list", [])
            cta = data.get("cta", "")

            if title:
                parts.append(f"# {title}")
            parts.append("| Shot # | Description | Camera | Audio | Notes |")
            parts.append("|--------|-------------|--------|-------|-------|")
            for i, shot in enumerate(shot_list, 1):
                shot_num = shot.get("shot", str(i))
                description = shot.get("description", "")
                camera = shot.get("camera", "")
                audio = shot.get("audio", "")
                notes = shot.get("notes", "")
                parts.append(
                    f"| {shot_num} | {description} | {camera} | {audio} | {notes} |"
                )
            if cta:
                parts.append(f"\n## Call to Action\n\n{cta}")

        elif video_type == "voiceover":
            title = data.get("title", "")
            voiceover = data.get("voiceover", "")
            cta = data.get("cta", "")

            if title:
                parts.append(f"# {title}")
            if voiceover:
                parts.append(f"## Voice-Over Script\n\n{voiceover}")
            if cta:
                parts.append(f"## Call to Action\n\n{cta}")

        elif video_type == "social":
            title = data.get("title", "")
            hook = data.get("hook", "")
            script = data.get("script", "")
            scenes = data.get("scenes", [])
            cta = data.get("cta", "")

            if title:
                parts.append(f"# {title}")
            if hook:
                parts.append(f"## Hook\n\n{hook}")
            if script:
                parts.append(f"## Script\n\n{script}")
            for i, scene in enumerate(scenes, 1):
                visual = scene.get("visual", "")
                voiceover = scene.get("voiceover", "")
                parts.append(
                    f"### Scene {i}\n\n"
                    f"**Visual:** {visual}\n\n"
                    f"**Voice-over (V.O.):** {voiceover}"
                )
            if cta:
                parts.append(f"## Call to Action\n\n{cta}")

        if not parts:
            return json.dumps(data, indent=2)

        return "\n\n".join(parts)

    def _build_prompt(
        self,
        video_type: str,
        topic: str,
        duration: str,
        video_type_detail: str,
        target_audience: str,
        tone: str,
        platform: str,
        cta: str,
        extra_context: str,
    ) -> str:
        """Select the matching template and inject variables safely."""
        template_map = {
            "script": VIDEO_SCRIPT_TEMPLATE,
            "storyboard": STORYBOARD_TEMPLATE,
            "shotlist": SHOT_LIST_TEMPLATE,
            "voiceover": VOICEOVER_SCRIPT_TEMPLATE,
            "social": SOCIAL_MEDIA_VIDEO_TEMPLATE,
        }

        template = template_map.get(video_type)
        if template is None:
            raise ValueError(f"Unknown video type: {video_type}")

        field_map = {
            "topic": topic,
            "video_type": video_type_detail or "explainer",
            "duration": duration,
            "target_audience": target_audience,
            "tone": tone,
            "cta": cta or "Visit our website to learn more",
            "platform": platform or "Instagram / TikTok",
            "product": extra_context or topic,
            "camera": extra_context or "professional video camera",
            "scene_count": self._estimate_scenes(duration),
        }

        prompt = template
        for key, value in field_map.items():
            placeholder = "{" + key + "}"
            prompt = prompt.replace(placeholder, str(value))

        return prompt

    @staticmethod
    def _estimate_scenes(duration: str) -> int:
        """
        Estimate the number of scenes based on duration.

        A 60-second video typically has 5–6 scenes, a 90-second video
        has 6–7, etc.  This is a rough heuristic for the storyboard
        template.
        """
        try:
            seconds = int(duration.split()[0])
        except (ValueError, IndexError):
            seconds = 60  # default fallback
        # Roughly one scene per 12 seconds, minimum 3
        return max(3, seconds // 12)

    def _get_demo_output(self, video_type: str, variant: int) -> str:
        """Return a pre-written demo output for the given video type."""
        outputs = DEMO_OUTPUTS.get(video_type, [])
        if not outputs:
            return "No demo output available for this content type."
        variant = variant % len(outputs)
        return outputs[variant]
